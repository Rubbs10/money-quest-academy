<p>假设你借给政府 1000 € 十年，它每年付你 3%（30 €），然后归还你的 1000 €。很简单。关键是：如果新债券开始付 5%，没人愿意以全价买你那张 3% 的债券，所以它的市场价格会下跌。这就是债券价格和利率反向变动的原因。</p>

